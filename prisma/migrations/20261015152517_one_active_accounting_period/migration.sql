-- Гонка в getActivePeriod() позволяла двум одновременным запросам создать
-- по новому активному периоду каждому, когда текущий истекал — оба успевали
-- увидеть "активного нет" до того, как любой из них зафиксировал запись.
-- Частичный уникальный индекс не даёт второй такой записи появиться в
-- принципе: вторая вставка падает с ошибкой уникальности, которую код
-- перехватывает и просто перечитывает уже созданный период.
CREATE UNIQUE INDEX "AccountingPeriod_one_active_idx" ON "AccountingPeriod"("status") WHERE "status" = 'active';
