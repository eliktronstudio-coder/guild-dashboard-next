/**
 * Разбор сообщений канала ренеймов: «СтарыйНик - НовыйНик».
 *
 * Отдельным модулем от index.js, чтобы разбор можно было проверить тестами:
 * именно здесь раньше молча терялись ники с пробелами.
 */

/** Должно совпадать с /api/bot/players/rename. */
const MAX_NICK = 40;

// Стрелку можно окружать чем угодно — она сама по себе однозначна.
const ARROW_RE = /^(.+?)\s*(?:->|=>|→|–|—)\s*(.+)$/;

// Дефис с пробелом хотя бы с одной стороны: «Крячка инактив- Abandonment»,
// «Старый Ник - Новый Ник». Пробел и есть признак того, что дефис здесь
// разделитель, а не часть слова, — поэтому имена могут состоять из
// нескольких слов.
const SPACED_HYPHEN_RE = /^(.+?)(?:\s+-\s*|\s*-\s+)(.+)$/;

// Дефис вообще без пробелов вокруг — «Кенвуд-Хренозавр». Принимаем, только
// если во всей строке нет пробелов: тогда это наверняка два ника, а не фраза.
// Именно это отличает «Кенвуд-Хренозавр» от «кто-нибудь тут?».
const TIGHT_HYPHEN_RE = /^(\S+)-(\S+)$/;

/** Ник обязан содержать хотя бы букву или цифру, а не только знаки. */
const HAS_ALNUM_RE = /[\p{L}\p{N}]/u;

/** Разбирает одну строку. null — строка не похожа на переименование. */
function parseRename(line) {
  const text = String(line ?? "").trim();
  if (!text) return null;

  const match = text.match(ARROW_RE) || text.match(SPACED_HYPHEN_RE) || text.match(TIGHT_HYPHEN_RE);
  if (!match) return null;

  const from = match[1].trim();
  const to = match[2].trim();
  if (!from || !to) return null;
  if (from.length > MAX_NICK || to.length > MAX_NICK) return null;

  // В каждой половине должна быть хотя бы буква или цифра. Без этой проверки
  // «Старый ->» разбиралось как переименование в ник «>»: остаток стрелки
  // попадал во вторую половину как обычный текст.
  if (!HAS_ALNUM_RE.test(from) || !HAS_ALNUM_RE.test(to)) return null;

  return { from, to };
}

/** Одно сообщение может содержать несколько переименований — по одному на строку. */
function parseRenames(content) {
  return String(content ?? "")
    .split("\n")
    .map(parseRename)
    .filter(Boolean);
}

/**
 * Похоже ли сообщение на попытку переименования: есть разделитель, но разбор
 * не удался. Нужно, чтобы подсказка не сыпалась на обычную болтовню в канале.
 */
function looksLikeRenameAttempt(content) {
  const text = String(content ?? "");
  // Стрелка однозначна; дефис — только когда рядом пробел. Дефис внутри слова
  // («кто-нибудь тут?») попыткой переименования не считаем, иначе подсказка
  // сыпалась бы на обычную речь.
  return /(?:->|=>|→|–|—)/.test(text) || /(?:^|\s)-|-(?:\s|$)/.test(text);
}

module.exports = { parseRename, parseRenames, looksLikeRenameAttempt, MAX_NICK };
